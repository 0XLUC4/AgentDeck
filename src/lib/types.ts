// Mirrors Rust types in src-tauri/src/{agents,hooks_server}. Keep in sync.

export type AgentKind = "claude" | "codex" | "gemini" | "grok" | "shell";

export interface AgentInfo {
  kind: AgentKind;
  installed: boolean;
  path: string | null;
  installUrl: string | null;
}

export type PaneStatus = "idle" | "working" | "waiting" | "done" | "error";

/** Payload of the `agent-status` event. */
export interface AgentStatusEvent {
  paneId: string;
  status: PaneStatus;
  lastAction: string | null;
  event: string;
}

export type VoiceState = "idle" | "listening" | "transcribing" | "error";

export interface SpawnOptions {
  /** Generated by the caller (crypto.randomUUID()); subscribe to output before spawning. */
  paneId: string;
  agent: AgentKind;
  cwd: string;
  args: string[];
  worktree: boolean;
  cols: number;
  rows: number;
}

/** A project folder currently open in an app (VS Code, Cursor, Explorer...). From `list_open_projects`. */
export interface OpenProject {
  app: string;
  name: string;
  path: string;
  isGit: boolean;
}

/** From `inspect_folder`. */
export interface FolderInfo {
  path: string;
  name: string;
  exists: boolean;
  isGit: boolean;
  branch: string | null;
  remote: string | null;
}
